#!/usr/bin/env python3
"""Generate waited global/LDS gfx90a pipelines with independent D/U.
All unresolved registers stay inside one opaque asm; no compiler slot rotation.
"""
import argparse
from math import gcd,lcm
from pathlib import Path

p=argparse.ArgumentParser()
p.add_argument('--depth',type=int,default=8)
p.add_argument('--unroll',type=int,default=32)
p.add_argument('--lds-stride',type=int,choices=(1,2,4,8),default=1)
p.add_argument('--ready-banks',type=int,choices=(0,1,2),default=2)
p.add_argument('--output',type=Path,required=True)
a=p.parse_args();D,U,S,R=a.depth,a.unroll,a.lds_stride,a.ready_banks
if not 1<=D<=16 or not 1<=U<=64:p.error('depth: 1..16; unroll: 1..64')
period=lcm(D,max(R,1));phases=period//gcd(period,U)
rawbase=0 if R==0 else 8
addr=rawbase+4*D;tmp=addr+2;last=tmp+3
out=['// Generated by generate.py; waits are mandatory.',
     f'constexpr int kDepth={D}, kUnroll={U}, kPhases={phases}, kLdsStride={S}, kReadyBanks={R};',
     'template<int Mode,int Loads> __device__ __forceinline__',
     'void pipeline(uint32_t blo,uint32_t bhi,uint32_t plo,uint32_t phi,',
     '              int steps,int records,F16& c,uint64_t& begin,uint64_t& end,',
     '              uint64_t& wall_begin,uint64_t& wall_end) {',
     '  uint32_t remaining=steps, offset=0, preleft=records;',
     '  const uint32_t window=uint32_t(records)*1024u*(Mode>=3?kLdsStride:1);']
for mode in range(5):
    lds=mode>=3;hot=mode in (0,3);wrap=mode in (1,4)
    record_bytes=1024*(S if lds else 1)
    counter='lgkmcnt' if lds else 'vmcnt'
    for loads in (1,2,4):
        threshold=min(loads*(D-1),14) if lds else loads*(D-1)
        lines=[];tag=f'm{mode}_l{loads}_d{D}_u{U}_s{S}_r{R}'
        def label(s):return f'.L{tag}_{s}'
        def emit(s):lines.append(s)
        def pointer(lo='blo',hi='bhi'):
            if lds:emit(f'v_add_u32 v{addr}, %[{lo}], %[offset]')
            else:
                emit(f'v_add_co_u32 v{addr}, vcc, %[{lo}], %[offset]')
                emit(f'v_addc_co_u32 v{addr+1}, vcc, %[{hi}], 0, vcc')
        def advance():
            if hot:return
            emit(f's_add_u32 %[offset], %[offset], {record_bytes}')
            if wrap:
                emit('s_cmp_ge_u32 %[offset], %[window]')
                emit('s_cselect_b32 %[offset], 0, %[offset]')
        def issue(dest):
            if not hot:pointer()
            ptr=f'v{addr}' if lds else f'v[{addr}:{addr+1}]'
            if loads==1:
                opcode='ds_read_b128' if lds else 'global_load_dwordx4'
                emit(f'{opcode} v[{dest}:{dest+3}], {ptr}'+('' if lds else ', off'))
            elif loads==2:
                opcode='ds_read_b64' if lds else 'global_load_dwordx2'
                end='' if lds else ', off'
                emit(f'{opcode} v[{dest}:{dest+1}], {ptr}{end}')
                emit(f'{opcode} v[{dest+2}:{dest+3}], {ptr}{end} offset:{512*(S if lds else 1)}')
            else:
                opcode='ds_read_b32' if lds else 'global_load_dword'
                for word in range(4):
                    suffix=f' offset:{word*256*(S if lds else 1)}' if word else ''
                    emit(f'{opcode} v{dest+word}, {ptr}'+('' if lds else ', off')+suffix)
            advance()
        # Global hot/L2 pre-read only. LDS is initialized by the CTA before asm.
        if mode in (0,1):
            emit('s_mov_b32 %[offset], 0');emit(label('prefetch')+':')
            pointer('plo','phi')
            emit(f'global_load_dwordx4 v[{tmp}:{tmp+3}], v[{addr}:{addr+1}], off')
            emit('s_waitcnt vmcnt(0)');emit('s_add_u32 %[offset], %[offset], 1024')
            emit('s_sub_u32 %[preleft], %[preleft], 1');emit('s_cmp_lg_u32 %[preleft], 0')
            emit('s_cbranch_scc1 '+label('prefetch'))
        emit('s_mov_b32 %[offset], 0')
        if hot:pointer()
        for ready in range(R):
            issue(4*ready);emit(f's_waitcnt {counter}(0)')
        def prime():
            for r in range(D-1):issue(rawbase+4*r)
        # Timer LGKM completion must not drain LDS raw priming before the loop.
        if not lds:prime()
        emit('s_memtime %[begin]');emit('s_waitcnt lgkmcnt(0)')
        emit('s_memrealtime %[wall_begin]');emit('s_waitcnt lgkmcnt(0)')
        if lds:prime()
        for phase in range(phases):
            emit(label(f'phase{phase}')+':')
            for j in range(U):
                n=phase*U+j;head=n%D;tail=(n+D-1)%D
                if R==0:
                    issue(rawbase+4*tail)
                    emit(f's_waitcnt {counter}({threshold})')
                    bank=rawbase+4*head
                    emit(f'v_mfma_f32_32x32x8f16 %[c], v[{bank}:{bank+1}], v[{bank+2}:{bank+3}], %[c]')
                else:
                    bank=4*(n%R)
                    emit(f'v_mfma_f32_32x32x8f16 %[c], v[{bank}:{bank+1}], v[{bank+2}:{bank+3}], %[c]')
                    issue(rawbase+4*tail)
                    emit(f's_waitcnt {counter}({threshold})')
                    for word in range(4):emit(f'v_mov_b32 v{bank+word}, v{rawbase+4*head+word}')
            emit(f's_sub_u32 %[remaining], %[remaining], {U}');emit('s_cmp_eq_u32 %[remaining], 0')
            if phases==1:emit('s_cbranch_scc0 '+label('phase0'))
            else:
                emit('s_cbranch_scc0 '+label(f'phase{(phase+1)%phases}'))
                emit('s_branch '+label('done'))
        emit(label('done')+':');emit(f's_waitcnt {counter}(0)')
        emit('s_memtime %[end]');emit('s_waitcnt lgkmcnt(0)')
        emit('s_memrealtime %[wall_end]');emit('s_waitcnt lgkmcnt(0)')
        # Guard accumulator extraction AFTER both timestamps, never the operands.
        for _ in range(4):emit('s_nop 15')
        out.append(f'  if constexpr(Mode=={mode} && Loads=={loads}) {{')
        out.append('    asm volatile(')
        for line in lines:out.append('      "'+line+'\\n\\t"')
        out+=['      : [c] "+a"(c), [remaining] "+&s"(remaining), [offset] "+&s"(offset),',
              '        [preleft] "+&s"(preleft), [begin] "=&s"(begin), [end] "=&s"(end),',
              '        [wall_begin] "=&s"(wall_begin), [wall_end] "=&s"(wall_end)',
              '      : [blo] "v"(blo), [bhi] "v"(bhi), [plo] "v"(plo), [phi] "v"(phi),',
              '        [window] "s"(window)',
              '      : "memory", "scc", "vcc", '+', '.join(f'"v{i}"' for i in range(last+1))+');','  }']
out+=['}'];a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text('\n'.join(out)+'\n')
print(f'Generated 15 waited entries: D={D}, U={U}, phases={phases}, LDS stride={S}, ready banks={R}, static MFMAs={phases*U}, private v0..v{last}')
