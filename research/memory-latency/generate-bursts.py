#!/usr/bin/env python3
"""Generate private asm batches: independent loads, then one completion wait."""
import sys
from pathlib import Path
lines=['// Generated by generate-bursts.py; no external code.','#pragma once',
       'template<int W,int D> struct Batch { using V=std::conditional_t<W==4,U4,uint32_t>; V value[D]; };',
       'template<int W,int D> __device__ __forceinline__ Batch<W,D> issue_batch(const uint32_t*,uint32_t&,uint32_t);']
for width in [1,4]:
 for depth in [1,2,4,8,16]:
  lines += [f'template<> __device__ __forceinline__ Batch<{width},{depth}> issue_batch<{width},{depth}>(const uint32_t* p,uint32_t& address,uint32_t stride) {{',f'  Batch<{width},{depth}> result;', '  asm volatile(']
  for i in range(depth):
   lines += [f'    "global_load_dword{"x4" if width==4 else ""} %{i}, %{depth}, %{depth+1}\\n\\t"',f'    "v_add_u32 %{depth}, %{depth+2}, %{depth}\\n\\t"']
  lines += ['    "s_waitcnt vmcnt(0)"', '    : '+','.join(f'"=&v"(result.value[{i}])'for i in range(depth))+',"+v"(address)', '    : "s"(p),"s"(stride) : "memory");','  return result;','}']
Path(sys.argv[1]).write_text('\n'.join(lines)+'\n')
